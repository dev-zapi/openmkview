#!/usr/bin/env bash
#
# Boot a scratch OpenMKView instance against the eval fixture project.
#
# Usage:
#   boot-fixture.sh [open|auth] [ROOT]
#
# Creates ROOT (default: a fresh ~/.cache/omk-eval.XXXXXX), copies the
# synthetic fixture project there, starts the server with OPENMKVIEW_DATA_HOME
# and OPENMKVIEW_CONFIG_HOME pointed inside ROOT, registers the fixture as a
# project, and writes ROOT/env.sh with everything a caller needs:
#
#   source "$ROOT/env.sh"
#   omk list --file README.md         # (omk alias below)
#
# The server keeps running until stop-fixture.sh is called (or the PID is
# killed). /tmp is deliberately avoided: the test machine has a quota there.
#
# Environment:
#   OPENMKVIEW_BIN     binary path (default: <repo>/target/debug/openmkview)
#   OPENMKVIEW_PORT    fixed port (default: an ephemeral free port)
#   OPENMKVIEW_USERNAME / OPENMKVIEW_PASSWORD   auth-mode credentials
#                      (defaults: alice / secret)

set -euo pipefail

MODE="${1:-open}"
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SKILL_DIR="$(cd "$SCRIPT_DIR/../.." && pwd)"
REPO_ROOT="$(cd "$SKILL_DIR/../.." && pwd)"
BIN="${OPENMKVIEW_BIN:-$REPO_ROOT/target/debug/openmkview}"
OMK="$SKILL_DIR/scripts/omk.mjs"
FIXTURE="$SKILL_DIR/evals/fixture"
USERNAME="${OPENMKVIEW_USERNAME:-alice}"
PASSWORD="${OPENMKVIEW_PASSWORD:-secret}"

if [[ "$MODE" != "open" && "$MODE" != "auth" ]]; then
  echo "usage: boot-fixture.sh [open|auth] [ROOT]" >&2
  exit 2
fi
if [[ ! -x "$BIN" ]]; then
  echo "FAIL: openmkview binary not found at $BIN (run: cargo build)" >&2
  exit 1
fi
if ! command -v curl >/dev/null 2>&1; then
  echo "FAIL: curl is required" >&2
  exit 1
fi

ROOT="${2:-}"
if [[ -z "$ROOT" ]]; then
  ROOT="$(mktemp -d "$HOME/.cache/omk-eval.XXXXXX")"
fi
mkdir -p "$ROOT/data" "$ROOT/config" "$ROOT/logs"
cp -r "$FIXTURE" "$ROOT/docs"

free_port() {
  if command -v node >/dev/null 2>&1; then
    node -e 'const net=require("node:net");const s=net.createServer();s.listen(0,"127.0.0.1",()=>{console.log(s.address().port);s.close();});'
  else
    python3 - <<'PY'
import socket
s = socket.socket()
s.bind(("127.0.0.1", 0))
print(s.getsockname()[1])
s.close()
PY
  fi
}

PORT="${OPENMKVIEW_PORT:-$(free_port)}"
URL="http://127.0.0.1:$PORT"
LOG="$ROOT/logs/server-$MODE.log"

if [[ "$MODE" == "auth" ]]; then
  OPENMKVIEW_DATA_HOME="$ROOT/data" \
  OPENMKVIEW_CONFIG_HOME="$ROOT/config" \
  OPENMKVIEW_USERNAME="$USERNAME" \
  OPENMKVIEW_PASSWORD="$PASSWORD" \
    "$BIN" serve --host 127.0.0.1 --port "$PORT" >"$LOG" 2>&1 &
else
  env -u OPENMKVIEW_USERNAME -u OPENMKVIEW_PASSWORD \
    OPENMKVIEW_DATA_HOME="$ROOT/data" \
    OPENMKVIEW_CONFIG_HOME="$ROOT/config" \
    "$BIN" serve --host 127.0.0.1 --port "$PORT" >"$LOG" 2>&1 &
fi
PID=$!
echo "$PID" > "$ROOT/pid"

cleanup_on_error() {
  if ! kill -0 "$PID" 2>/dev/null; then
    echo "FAIL: server exited; see $LOG" >&2
    tail -20 "$LOG" >&2 || true
  fi
}
trap cleanup_on_error ERR

ready=0
for _ in $(seq 1 150); do
  if curl -sf "$URL/api/auth/status" >/dev/null 2>&1; then ready=1; break; fi
  sleep 0.1
done
if [[ "$ready" -ne 1 ]]; then
  echo "FAIL: server did not become ready at $URL; see $LOG" >&2
  kill "$PID" 2>/dev/null || true
  exit 1
fi

AUTH_HEADER=()
TOKEN=""
if [[ "$MODE" == "auth" ]]; then
  exchange="$ROOT/tool-session.json"
  curl -sf -X POST "$URL/api/auth/tool-sessions/exchange" \
    -H 'Content-Type: application/json' \
    -d "{\"username\":\"$USERNAME\",\"password\":\"$PASSWORD\",\"label\":\"eval-fixture-$MODE\"}" \
    >"$exchange"
  TOKEN="$(node -e 'const fs=require("node:fs");process.stdout.write(JSON.parse(fs.readFileSync(process.argv[1],"utf8")).token)' "$exchange")"
  AUTH_HEADER=(-H "Authorization: Bearer $TOKEN")
fi

project_json="$ROOT/project.json"
curl -sf -X POST "$URL/api/projects" \
  "${AUTH_HEADER[@]}" \
  -H 'Content-Type: application/json' \
  -d "{\"path\":\"$ROOT/docs\"}" >"$project_json"
PROJECT_ID="$(node -e 'const fs=require("node:fs");process.stdout.write(String(JSON.parse(fs.readFileSync(process.argv[1],"utf8")).id))' "$project_json")"

AGENT_CONFIG="$ROOT/agent.json"

cat >"$ROOT/env.sh" <<EOF
# Generated by boot-fixture.sh — source me.
export EVAL_MODE="$MODE"
export EVAL_ROOT="$ROOT"
export OPENMKVIEW_URL="$URL"
export OPENMKVIEW_AGENT_CONFIG="$AGENT_CONFIG"
export OPENMKVIEW_BIN="$BIN"
export OPENMKVIEW_EVAL_PROJECT_ID="$PROJECT_ID"
export OPENMKVIEW_EVAL_TOKEN="$TOKEN"
export OPENMKVIEW_EVAL_PID="$PID"
export OPENMKVIEW_EVAL_USERNAME="$USERNAME"
export OPENMKVIEW_EVAL_PASSWORD="$PASSWORD"
cd "$REPO_ROOT"
EOF

echo "mode=$MODE"
echo "url=$URL"
echo "root=$ROOT"
echo "project_id=$PROJECT_ID"
echo "pid=$PID"
echo "env=$ROOT/env.sh"
